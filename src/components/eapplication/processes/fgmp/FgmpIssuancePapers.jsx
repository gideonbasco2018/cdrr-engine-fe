/* Everything the two documents need, gathered from the application */
export function buildIssuanceDoc(data, formData = {}, provisionalCertNo = null) {
  const ops = data?.orders_of_payment || [];
  const initial = ops.find((op) => op.op_type === "INITIAL") || ops[0] || null;
  const receipts = ops.flatMap((op) => op.verifications || []);
  const latest = receipts[receipts.length - 1] || null;

  return {
    manufacturer: data?.foreign_manufacturer,
    plantAddress: data?.foreign_manufacturer_address,
    productLine: data?.product_line,
    importer: data?.applicant_company,
    importerAddress: data?.address,
    // the FGMP form calls it "LTO Number" while the claim reads "LTO No."
    ltoNumber: data?.lto_no || formData["LTO Number"] || formData["LTO No."],
    certificateNumber: data?.certificate_number || provisionalCertNo,
    // true while it is only the number this would get, not one it holds
    certificateNumberProvisional:
      !data?.certificate_number && !!provisionalCertNo,
    // the extension letter quotes the certificate it extends
    previousCertificateNumber: data?.previous_certificate_number,
    manufacturerCountry: data?.foreign_manufacturer_country,
    applicationType: data?.application_type,
    referenceNumber: data?.reference_number,
    amount: initial ? Number(initial.total_amount) : null,
    orNumberDate: latest
      ? `${latest.official_receipt_number} / ${longDate(latest.date_of_payment)}`
      : null,
    dateIssued: longDate(new Date()),
  };
}
