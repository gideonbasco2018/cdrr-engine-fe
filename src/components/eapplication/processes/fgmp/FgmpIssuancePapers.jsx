/* ── Letter of Disapproval ──────────────────────────────────────────────
   Three letters share a shape but differ in why the application failed:
     "requirements" — the documents listed below were never submitted
     "inspection"   — an FDA inspection found critical/major deficiencies
     "nod"          — the Notice of Deficiency was never answered           */

const MISSING_REQUIREMENTS = [
  "Acceptable GMP Evidence issued by Pharmaceutical Inspection Cooperation Scheme (PIC/S), Association of Southeast Asian Nations Mutual Recognition Arrangement (ASEAN MRA), and/or World Health Organization (WHO) Pre-qualification Team",
  "Copy of last inspection report and if any, Corrective Action and Preventive Action (CAPA) to the deficiencies noted",
  "Copy of GMP Contract between the manufacturer and the importer, including a list of specific products for supply in the Philippines",
  "Site Master File",
  "Validation Master File",
  "Rationale for test method validation, procedure for method transfer etc.",
  "Procedure for handling deviations and OOS",
];

export function LetterOfDisapprovalPaper({ doc, reason = "requirements" }) {
  const viaEvaluation = reason !== "inspection";
  return (
    <>
      <div style={titleStyle}>LETTER OF DISAPPROVAL</div>
      <LetterOpening doc={doc} />

      <p style={{ margin: "0 0 0.9rem", textAlign: "justify" }}>
        This refers to your application for Good Manufacturing Practice (GMP)
        Clearance{viaEvaluation ? " via GMP Evidence Evaluation" : ""} for your
        foreign drug manufacturer{" "}
        <strong>{doc.manufacturer || <Blank hint="foreign manufacturer" />}</strong>{" "}
        with address at{" "}
        <strong>{doc.plantAddress || <Blank hint="plant address" />}</strong>{" "}
        {viaEvaluation ? "and reference number of" : "under reference number"}{" "}
        <strong>{doc.referenceNumber || <Blank hint="reference number" />}</strong>.
      </p>

      {reason === "requirements" && (
        <>
          <p style={{ margin: "0 0 0.5rem", textAlign: "justify" }}>
            Please be informed that upon careful evaluation of the application,
            the following requirements were not submitted:
          </p>
          <ul style={{ margin: "0 0 0.9rem 1.2rem", padding: 0 }}>
            {MISSING_REQUIREMENTS.map((item) => (
              <li
                key={item}
                style={{ marginBottom: "0.25rem", textAlign: "justify" }}
              >
                {item}
              </li>
            ))}
          </ul>
        </>
      )}

      {reason === "inspection" && (
        <p style={{ margin: "0 0 0.9rem", textAlign: "justify" }}>
          Please be informed that the manufacturer’s{" "}
          <Blank width="150px" hint="audited areas" /> were inspected by the FDA
          Philippines inspectorate dated{" "}
          <Blank width="130px" hint="inspection date" /> and was found with
          critical and major deficiencies relevant to sections of PIC/S GMP
          Guide (Part I and its Annexes). Summary of deficiencies were listed in
          the inspection report and conformed by the manufacturer’s
          representative <Blank width="160px" hint="key personnel" /> (see
          attached).
        </p>
      )}

      {reason === "nod" && (
        <p style={{ margin: "0 0 0.9rem", textAlign: "justify" }}>
          Please be informed that upon careful evaluation of the application, it
          was noted that you have failed to submit acceptable compliance to the
          Notice of Deficiency/ies (NOD) sent thru e-mail last{" "}
          <Blank width="140px" hint="date the NOD was e-mailed" /> (see attached
          communication for your reference).
        </p>
      )}

      <p style={{ margin: "0 0 0.9rem", textAlign: "justify" }}>
        In view of the foregoing, your application
        {reason === "inspection" ? (
          <>
            {" "}
            for GMP clearance on its{" "}
            <strong>{doc.productLine || <Blank hint="product line" />}</strong>{" "}
            is hereby <strong>DISAPPROVED</strong>, pursuant to Administrative
            Order No. 2013-0022 and Section IV, 5(b) of FDA Circular No.
            2014-016 “Decision after Foreign Drug Manufacturer GMP Inspection.”
          </>
        ) : reason === "nod" ? (
          <>
            {" "}
            is hereby <strong>DISAPPROVED</strong>, pursuant to item B (1),
            Section 4. Grounds for Disapproval of Application, Article I, Book
            II of The Rules and Regulation Implementing Republic Act No. 9711.
          </>
        ) : (
          <>
            {" "}
            is hereby <strong>DISAPPROVED</strong>, pursuant to A.9, Section
            VII. Documentary Requirements of Administrative Order No. 2013-0022.
          </>
        )}
      </p>

      <p style={{ margin: "0 0 1.2rem", textAlign: "justify" }}>
        Should you wish to pursue your application, you{" "}
        {reason === "inspection"
          ? "can re-apply six (6) months after receipt of this letter with complete requirements"
          : "need to re-apply with complete requirements"}{" "}
        and pay the corresponding fee as initial application.
      </p>

      <p style={{ margin: "0 0 0.2rem" }}>Very truly yours,</p>
      <Signature
        centre={
          reason === "inspection"
            ? "Center for Drug Regulation and Research"
            : undefined
        }
      />

      <FooterRows
        rows={[
          ["LTO No.", doc.ltoNumber || <Blank />],
          ["Reg. Fee", doc.amount != null ? php(doc.amount) : <Blank />],
          ["O.R. No. / Date", doc.orNumberDate || <Blank />],
        ]}
      />

      <p style={{ marginTop: "0.8rem", fontSize: "12px" }}>Cc: CDRR-PRSDD</p>
    </>
  );
}

